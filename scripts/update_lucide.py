#!/usr/bin/env python3
"""Download the latest stable Lucide release and regenerate Lemon's bundled icons.

From the repository root: python3 scripts/update_lucide.py
Requires Python 3, rustfmt and network access. No Python packages are needed.
The generated catalog records the exact release and its upstream source URL.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path, PurePosixPath
from urllib.parse import quote
from urllib.request import Request, urlopen

RELEASE_API = "https://api.github.com/repos/lucide-icons/lucide/releases/latest"


def latest_release():
    request = Request(RELEASE_API, headers={
        "Accept": "application/vnd.github+json", "User-Agent": "lemon-update-lucide",
    })
    with urlopen(request, timeout=60) as response:
        release = json.load(response)
    tag = release.get("tag_name")
    if not isinstance(tag, str) or not tag or release.get("draft") or release.get("prerelease"):
        raise ValueError("GitHub did not return a stable Lucide release")
    return tag


def read_archive(path):
    """Read only regular SVG/license files; never extract paths onto disk."""
    icons, license_text = [], None
    roots = set()
    with tarfile.open(path, "r:gz") as archive:
        for member in archive:
            member_path = PurePosixPath(member.name)
            if member_path.is_absolute() or ".." in member_path.parts:
                raise ValueError(f"Unsafe archive path: {member.name}")
            if not member.isfile():
                continue
            parts = member_path.parts
            is_license = len(parts) == 2 and parts[1] == "LICENSE"
            is_icon = len(parts) == 3 and parts[1] == "icons" and member_path.suffix == ".svg"
            if not (is_license or is_icon):
                continue
            if is_icon and not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*\.svg", member_path.name):
                raise ValueError(f"Unsupported icon filename: {member_path.name}")
            source = archive.extractfile(member)
            if source is None:
                raise ValueError(f"Cannot read archive member: {member.name}")
            with source:
                content = source.read()
            roots.add(parts[0])
            if is_license:
                license_text = content.decode("utf-8")
            else:
                icons.append((member_path.stem, content))
    if len(roots) != 1 or not icons or not license_text:
        raise ValueError("Release archive must contain one icon directory and a nonempty LICENSE")
    return sorted(icons, key=lambda item: item[0] + ".svg"), license_text


def shape_path(element):
    a = element.attrib
    tag = element.tag.split('}')[-1]
    if tag == 'path':
        data = a['d'].strip()
        # Each SVG shape starts at the origin; concatenation must preserve that.
        return 'M0 0 ' + data if data.startswith('m') else data
    if tag in ('polyline', 'polygon'):
        points = re.findall(r'-?(?:\d*\.)?\d+', a['points'])
        return 'M' + ' '.join(points) + ('Z' if tag == 'polygon' else '')
    if tag == 'line':
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ('circle', 'ellipse'):
        cx, cy = float(a['cx']), float(a['cy'])
        rx, ry = (float(a['r']), float(a['r'])) if tag == 'circle' else (float(a['rx']), float(a['ry']))
        return f'M{cx-rx:g} {cy:g}a{rx:g} {ry:g} 0 1 0 {rx*2:g} 0a{rx:g} {ry:g} 0 1 0 {-rx*2:g} 0Z'
    if tag == 'rect':
        x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
        rx = min(float(a.get('rx', a.get('ry', 0))), w / 2)
        ry = min(float(a.get('ry', a.get('rx', 0))), h / 2)
        if rx == 0 or ry == 0:
            return f'M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z'
        return (f'M{x+rx:g} {y:g}H{x+w-rx:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {ry:g}'
                f'V{y+h-ry:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {ry:g}'
                f'H{x+rx:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {-ry:g}'
                f'V{y+ry:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {-ry:g}Z')
    raise ValueError(f'Unsupported SVG shape: {tag}')


def generate_catalog(icons, tag):
    output = [f'//! Lucide vector icons, vendored from upstream release `{tag}`.',
              f'//! Source: <https://github.com/lucide-icons/lucide/releases/tag/{quote(tag, safe="")}>',
              '//! Generated by `scripts/update_lucide.py`; see `licenses/lucide-LICENSE`.',
              '', 'use super::IconData;', '']
    names, seen = [], set()
    for slug, content in icons:
        svg = ET.fromstring(content)
        if svg.attrib.get('viewBox') != '0 0 24 24':
            raise ValueError(f'Unsupported viewBox: {slug}')
        strokes, fills = [], []
        for element in svg:
            if not set(element.attrib).isdisjoint({'transform', 'style'}):
                raise ValueError(f'Unsupported SVG transform/style: {slug}')
            data = shape_path(element)
            strokes.append(data)
            if element.attrib.get('fill') == 'currentColor':
                fills.append(data)
        name = slug.replace('-', '_').upper()
        if name[0].isdigit():
            name = 'ICON_' + name
        if name in seen or not strokes:
            raise ValueError(f'Duplicate or empty icon: {slug}')
        seen.add(name)
        names.append(name)
        output += [f'/// Lucide `{slug}` icon (24 × 24 stroke grid).',
                   f'pub const {name}: IconData = IconData {{',
                   f'    name: {json.dumps(slug)},',
                   f'    stroke: {json.dumps(" ".join(strokes))},',
                   f'    fill: {json.dumps(" ".join(fills))},', '};', '']
    if not names:
        raise ValueError('No SVG icons found')
    output += ['/// Every icon in the bundled Lucide catalog, ordered by name.',
               'pub const ALL: &[IconData] = &[']
    output += [f'    {name},' for name in names]
    output += ['];', '']
    return '\n'.join(output)


def update_catalog(root, archive, tag):
    icons, license_text = read_archive(archive)
    catalog = generate_catalog(icons, tag)
    formatted = subprocess.run(
        ['rustfmt', '--edition', '2021', '--emit', 'stdout'],
        input=catalog, text=True, capture_output=True, check=True,
    ).stdout
    # Keep staging on the repository filesystem so each replacement is atomic.
    # Download, conversion and formatting must all succeed before any replacement.
    with tempfile.TemporaryDirectory(prefix='.lucide-', dir=root) as staging:
        catalog_path = Path(staging) / 'lucide.rs'
        license_path = Path(staging) / 'LICENSE'
        catalog_path.write_text(formatted, encoding='utf-8')
        license_path.write_text(license_text, encoding='utf-8')
        os.replace(catalog_path, root / 'src/icons/lucide.rs')
        os.replace(license_path, root / 'licenses/lucide-LICENSE')
    return len(icons)


def main():
    root = Path(__file__).resolve().parents[1]
    tag = latest_release()
    print(f'Downloading Lucide {tag}…', flush=True)
    url = f'https://codeload.github.com/lucide-icons/lucide/tar.gz/{quote(tag, safe="")}'
    request = Request(url, headers={'User-Agent': 'lemon-update-lucide'})
    with tempfile.TemporaryDirectory(prefix='lemon-lucide-') as temporary:
        archive = Path(temporary) / 'release.tar.gz'
        with urlopen(request, timeout=60) as response, archive.open('wb') as target:
            shutil.copyfileobj(response, target)
        count = update_catalog(root, archive, tag)
    print(f'Updated {count} icons and license from Lucide {tag}.')


if __name__ == '__main__':
    if len(sys.argv) != 1:
        sys.exit('Usage: python3 scripts/update_lucide.py')
    try:
        main()
    except (OSError, ValueError, KeyError, ET.ParseError, tarfile.TarError,
            subprocess.CalledProcessError) as error:
        sys.exit(f'Lucide update failed: {error}')
