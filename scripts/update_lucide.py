#!/usr/bin/env python3
"""Regenerate Lemon's Lucide catalog from an extracted upstream source checkout.

Usage: python3 scripts/update_lucide.py /path/to/lucide
Pinned source: https://github.com/lucide-icons/lucide/tree/20aef31db93fe4d9f398dbb15b120d99c48eef95
"""
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

def shape_path(element):
    a = element.attrib
    tag = element.tag.split('}')[-1]
    if tag == 'path':
        return a['d']
    if tag in ('polyline', 'polygon'):
        points = re.findall(r'-?(?:\d*\.)?\d+', a['points'])
        return 'M' + ' '.join(points) + ('Z' if tag == 'polygon' else '')
    if tag == 'line':
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ('circle', 'ellipse'):
        cx, cy = float(a['cx']), float(a['cy'])
        rx, ry = (float(a['r']), float(a['r'])) if tag == 'circle' else (float(a['rx']), float(a['ry']))
        return f'M{cx-rx:g} {cy:g}a{rx:g} {ry:g} 0 1 0 {rx*2:g} 0a{rx:g} {ry:g} 0 1 0 {-rx*2:g} 0Z'
    if tag == 'rect':
        x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
        rx = min(float(a.get('rx', a.get('ry', 0))), w / 2)
        ry = min(float(a.get('ry', a.get('rx', 0))), h / 2)
        if rx == 0 or ry == 0:
            return f'M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z'
        return (f'M{x+rx:g} {y:g}H{x+w-rx:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {ry:g}'
                f'V{y+h-ry:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {ry:g}'
                f'H{x+rx:g}a{rx:g} {ry:g} 0 0 1 {-rx:g} {-ry:g}'
                f'V{y+ry:g}a{rx:g} {ry:g} 0 0 1 {rx:g} {-ry:g}Z')
    raise ValueError(f'Unsupported SVG shape: {tag}')


def main(source):
    root = Path(__file__).resolve().parents[1]
    output = ['//! Lucide vector icons, vendored from upstream commit',
              '//! `20aef31db93fe4d9f398dbb15b120d99c48eef95`.',
              '//! Generated by `scripts/update_lucide.py`; see `licenses/lucide-LICENSE`.',
              '', 'use super::IconData;', '']
    names = []
    for path in sorted((source / 'icons').glob('*.svg')):
        svg = ET.parse(path).getroot()
        assert svg.attrib['viewBox'] == '0 0 24 24', path
        strokes, fills = [], []
        for element in svg:
            assert set(element.attrib).isdisjoint({'transform', 'style'}), path
            data = shape_path(element)
            strokes.append(data)
            if element.attrib.get('fill') == 'currentColor':
                fills.append(data)
        name = path.stem.replace('-', '_').upper()
        if name[0].isdigit():
            name = 'ICON_' + name
        assert name not in names, name
        names.append(name)
        output += [f'/// Lucide `{path.stem}` icon (24 × 24 stroke grid).',
                   f'pub const {name}: IconData = IconData {{',
                   f'    name: {json.dumps(path.stem)},',
                   f'    stroke: {json.dumps(" ".join(strokes))},',
                   f'    fill: {json.dumps(" ".join(fills))},', '};', '']
    assert names, 'No SVG icons found'
    output += ['/// Every icon in the bundled Lucide catalog, ordered by name.',
               'pub const ALL: &[IconData] = &[']
    output += [f'    {name},' for name in names]
    output += ['];', '']
    (root / 'src/icons/lucide.rs').write_text('\n'.join(output))
    (root / 'licenses/lucide-LICENSE').write_text((source / 'LICENSE').read_text())
    print(f'Generated {len(names)} icons')


if __name__ == '__main__':
    main(Path(sys.argv[1]))
